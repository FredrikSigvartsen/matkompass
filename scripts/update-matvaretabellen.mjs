const response = await fetch(API_URL);

if (!response.ok) {
  throw new Error(`Matvaretabellen svarte med ${response.status}`);
}

const { foods } = await response.json();
const foodsById = new Map(foods.map((food) => [food.foodId, food]));

function getNutrient(food, nutrientId) {
  return (
    food.constituents.find((item) => item.nutrientId === nutrientId)?.quantity ?? 0
  );
}

const selectedFoods = selectedFoodIds.map((foodId) => {
  const food = foodsById.get(foodId);

  if (!food) {
    throw new Error(`Fant ikke matvare ${foodId}`);
  }

  return {
    id: food.foodId,
    name: food.foodName,
    uri: food.uri,
    per100g: {
      calories: food.calories.quantity,
      protein: getNutrient(food, "Protein"),
      fat: getNutrient(food, "Fett"),
      carbs: getNutrient(food, "Karbo"),
    },
  };
});

const output = `// Generated by scripts/update-matvaretabellen.mjs. Do not edit manually.
export const foodDataSource = {
  name: "Matvaretabellen 2026",
  url: "${API_URL}",
  retrievedAt: "${new Date().toISOString().slice(0, 10)}",
} as const;

export const foods = ${JSON.stringify(selectedFoods, null, 2)} as const;
`;

await writeFile(OUTPUT_PATH, output);
console.log(`Skrev ${selectedFoods.length} matvarer til ${OUTPUT_PATH.pathname}`);
